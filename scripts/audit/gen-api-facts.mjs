#!/usr/bin/env node
// @purpose Generates docs/spec/API_FACTS.md — the verified ground truth of what exists in src/ (events, store, audio keys, textures, public methods).
// Run: node scripts/audit/gen-api-facts.mjs   (never hand-edit the output)
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const walk = (dir) =>
  fs.readdirSync(path.join(root, dir), { withFileTypes: true }).flatMap((e) => {
    const rel = path.join(dir, e.name);
    return e.isDirectory() ? walk(rel) : [rel];
  });

const out = [];
const h = (s) => out.push(`\n## ${s}\n`);
const uniq = (a) => [...new Set(a)].sort();

const pkg = JSON.parse(read("package.json"));
out.push("# API_FACTS.md — GENERATED ground truth (do not hand-edit)");
out.push(`> Generated by \`node scripts/audit/gen-api-facts.mjs\` on ${new Date().toISOString().slice(0, 10)}. If a name is **not in this file**, it does **not exist yet** — create it (and tag it \`[NEW]\` in specs) or ask. Never assume. Method parameter text is truncated for width — open the file for the exact signature.`);

h("1. Pinned versions (package.json)");
for (const k of ["next", "react", "phaser", "zustand", "framer-motion", "mitt", "zod", "tailwindcss", "vitest", "@playwright/test", "@mediapipe/tasks-vision"]) {
  const v = pkg.dependencies?.[k] ?? pkg.devDependencies?.[k];
  if (v) out.push(`- \`${k}\`: ${v}`);
}

h("2. Event bus — `src/game/bus.ts` (`gameBus`, mitt)");
const bus = read("src/game/bus.ts");
const busBody = bus.slice(bus.indexOf("GameEventTypes"), bus.indexOf("\n};"));
const keyRe = /^\s{2}"([^"]+)":/gm;
const keys = [...busBody.matchAll(keyRe)];
keys.forEach((k, i) => {
  const end = i + 1 < keys.length ? keys[i + 1].index : busBody.length;
  const payload = busBody.slice(k.index + k[0].length, end).replace(/\/\/.*$/gm, "").replace(/\s+/g, " ").trim().replace(/;$/, "");
  out.push(`- \`${k[1]}\` → \`${payload}\``);
});

h("3. Zustand store — `src/store/useGameStore.ts` (`useGameStore`)");
const store = read("src/store/useGameStore.ts");
const iface = store.slice(store.indexOf("export interface GameState"), store.indexOf("\n}\n", store.indexOf("export interface GameState")));
const state = [], actions = [];
for (const m of iface.matchAll(/^\s{2}(\w+):\s*(.+?);\s*(?:\/\/.*)?$/gm)) (m[2].includes("=>") ? actions : state).push(`${m[1]}: ${m[2]}`);
out.push("**State:**"); state.forEach((s) => out.push(`- \`${s}\``));
out.push("\n**Actions:**"); actions.forEach((s) => out.push(`- \`${s}\``));

h("4. Audio — `src/services/audio.ts` (`audioService`) — 100% WebAudio synth, NO sample/TTS playback exists");
const audio = read("src/services/audio.ts");
out.push("**Public methods:**");
uniq([...audio.matchAll(/^\s{2}public\s+(?:async\s+)?(\w+)\(([^)]*)\)/gm)].map((m) => `- \`${m[1]}(${m[2].replace(/\s+/g, " ")})\``)).forEach((l) => out.push(l));
out.push(`\n**Sound keys accepted by \`play()\`/\`playSpatial()\`:** ${uniq([...audio.matchAll(/case "([a-z0-9-]+)"/g)].map((m) => m[1])).map((k) => `\`${k}\``).join(", ")}`);
const mv = audio.match(/maxSimultaneousVoices\s*=\s*(\d+)/);
out.push(`\n**Hard limit:** \`maxSimultaneousVoices = ${mv ? mv[1] : "?"}\` (shared by ALL synth SFX — voice/crowd audio needs its own channel).`);

h("5. Phaser texture keys that exist");
const boot = read("src/game/scenes/BootScene.ts");
const procedural = uniq([...boot.matchAll(/(?:generateTexture|addCanvas)\(\s*"([\w-]+)"/g)].map((m) => m[1]));
out.push(`**Procedural (BootScene):** ${procedural.map((k) => `\`${k}\``).join(", ")}`);
const pre = read("src/game/scenes/PreloadScene.ts");
const svg = uniq([...pre.matchAll(/key:\s*"([\w-]+)",\s*url:\s*"([^"]+)"/g)].map((m) => m[1]));
out.push(`\n**SVG preloaded (PreloadScene) — ${svg.length} keys:** ${svg.map((k) => `\`${k}\``).join(", ")}`);
out.push("\n> Other textures may be created dynamically (loops/templates) in BootScene; grep before claiming one is missing.");

h("6. Public methods of game systems & entities");
for (const f of walk("src/game").filter((f) => /\/(systems|entities|fx)\//.test(f) && f.endsWith(".ts"))) {
  const src = read(f);
  const cls = [...src.matchAll(/export class (\w+)/g)].map((m) => m[1]).join(", ");
  const methods = uniq([...src.matchAll(/^\s{2}public\s+(?:async\s+|static\s+)?(\w+)\(([^)]*)\)/gm)].map((m) => `${m[1]}(${m[2].replace(/\s+/g, " ").slice(0, 60)})`));
  out.push(`- \`${f}\` — **${cls || "(no class)"}**: ${methods.length ? methods.map((m) => `\`${m}\``).join(", ") : "—"}`);
}

h("7. Config modules (`src/config/*`) and their exports");
for (const f of walk("src/config")) {
  if (!/\.(ts|json)$/.test(f)) continue;
  if (f.endsWith(".json")) { out.push(`- \`${f}\` (JSON)`); continue; }
  const ex = uniq([...read(f).matchAll(/^export (?:const|function|interface|type|class) (\w+)/gm)].map((m) => m[1]));
  out.push(`- \`${f}\`: ${ex.map((e) => `\`${e}\``).join(", ")}`);
}

h("8. Ids that exist");
const ids = (f, re) => uniq([...read(f).matchAll(re)].map((m) => m[1]));
out.push(`- Villain archetype ids: ${ids("src/config/villains.ts", /^\s{4}id:\s*"(\w+)"/gm).map((i) => `\`${i}\``).join(", ")}`);
out.push(`- Map ids (currently a closed union of 3): ${ids("src/config/maps.ts", /^\s{4}id:\s*"(\w+)"/gm).map((i) => `\`${i}\``).join(", ")}`);
out.push(`- Obstacle types: ${[...read("src/game/entities/Obstacle.ts").matchAll(/\|\s*"([\w-]+)"/g)].map((m) => `\`${m[1]}\``).join(", ")}`);
out.push(`- Dialogue groups (\`DIALOGUE_GROUPS\`): ${[...read("src/config/dialogue.ts").matchAll(/^\s{2}(\w+):\s*\[/gm)].map((m) => `\`${m[1]}\``).join(", ")}`);

h("9. Source tree (lines)");
for (const f of walk("src").filter((f) => /\.(ts|tsx|json|css)$/.test(f) && !f.includes("__tests__")).sort()) out.push(`- \`${f}\` (${read(f).split("\n").length})`);

h("10. Gates");
out.push("`npx tsc --noEmit` · `npm run lint` · `npm run test` (vitest) · `npm run build` · `npx playwright test`");

fs.mkdirSync(path.join(root, "docs/spec"), { recursive: true });
fs.writeFileSync(path.join(root, "docs/spec/API_FACTS.md"), out.join("\n") + "\n");
console.log("wrote docs/spec/API_FACTS.md");
